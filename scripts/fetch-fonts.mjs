// Downloads Inter + Fraunces from Google Fonts (woff2) and generates fonts.css.
// Run: node scripts/fetch-fonts.mjs
import { mkdir, writeFile, readdir, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const fontsDir = join(root, 'renderer', 'fonts');
const cssOut = join(root, 'renderer', 'fonts.css');

const FAMILIES = [
  'family=Inter:wght@400;500;600',
  'family=Fraunces:ital,opsz,wght@0,9..144,400..600;1,9..144,400..600'
];
const CSS_URL = `https://fonts.googleapis.com/css2?${FAMILIES.join('&')}&display=swap`;

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

function escCss(text) {
  return text.replace(/\\"/g, '"').replace(/\\\\/g, '\\').replace(/\\'|"/g, "'");
}

async function fetchText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return res.text();
}

async function download(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

await rm(fontsDir, { recursive: true, force: true });
await mkdir(fontsDir, { recursive: true });

const css = await fetchText(CSS_URL);
const faceRegex = /@font-face\s*\{[^}]+\}/g;
const urlRegex = /url\((https:\/\/fonts\.gstatic\.com\/[^)]+?)\)/g;

const faces = css.match(faceRegex) ?? [];
if (faces.length === 0) throw new Error('No @font-face blocks found in CSS response');

const used = new Set();
let rewritten = '/* Generated by scripts/fetch-fonts.mjs — do not edit by hand. */\n';

for (const face of faces) {
  const rewrittenFace = face.replace(urlRegex, (_, url) => {
    const name = url.split('/').pop();
    const safe = name.replace(/[^a-zA-Z0-9._-]/g, '_');
    let final = safe;
    let n = 2;
    while (used.has(final)) final = `${safe.replace(/\.[a-z0-9]+$/i, '')}-${n++}.woff2`;
    used.add(final);
    return `url(fonts/${final})`;
  });
  rewritten += `${rewrittenFace}\n`;
}

// Collect unique file names referenced, download them.
const seen = new Set();
for (const face of faces) {
  for (const match of face.matchAll(urlRegex)) {
    const url = match[1];
    const name = url.split('/').pop();
    const safe = name.replace(/[^a-zA-Z0-9._-]/g, '_');
    let final = safe;
    let n = 2;
    while (seen.has(final)) final = `${safe.replace(/\.[a-z0-9]+$/i, '')}-${n++}.woff2`;
    seen.add(final);
    const buf = await download(url);
    await writeFile(join(fontsDir, final), buf);
    console.log(`downloaded ${final} (${(buf.length / 1024).toFixed(1)} KB)`);
  }
}

await writeFile(cssOut, rewritten);
console.log(`Wrote ${cssOut}`);
console.log('Families referenced in css:');
for (const m of css.matchAll(/font-family:\s*'([^']+)'/g)) console.log(`  - ${m[1]}`);
